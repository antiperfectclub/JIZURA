"""Bundle Cavalry's host runtime and panel for the browser build and the dist folder."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
browser = (ROOT / 'cavalry/browser.js').read_text(encoding='utf-8')
runtime = (ROOT / 'cavalry/runtime.js').read_text(encoding='utf-8')
panel = (ROOT / 'cavalry/panel.js').read_text(encoding='utf-8')


def literal(text):
    # Safe even when the source contains an HTML script closing tag.
    return json.dumps(text, ensure_ascii=True).replace('<', '\\u003c')


source = ('/* GENERATED by build_cavalry.py. Do not edit. */\n' + browser
          + '\nJ.Cavalry.runtimeSource = ' + literal(runtime)
          + ';\nJ.Cavalry.panelSource = ' + literal(panel) + ';\n')
(ROOT / 'src/11r_cavalry.js').write_text(source, encoding='utf-8')
print('Generated src/11r_cavalry.js')

dist = ROOT / 'dist' / 'cavalry'
dist.mkdir(parents=True, exist_ok=True)
(dist / 'JIZURA_Cavalry.js').write_text(
    "/* GENERATED. Install in Cavalry: Help > Show Scripts Folder, then Window > Scripts > JIZURA. */\n"
    + runtime + '\n' + panel + '\n', encoding='utf-8')
print('Generated dist/cavalry/JIZURA_Cavalry.js')
