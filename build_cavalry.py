"""Bundle Cavalry's host runtime as data for the existing browser build."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
browser = (ROOT / 'cavalry/browser.js').read_text(encoding='utf-8')
runtime = (ROOT / 'cavalry/runtime.js').read_text(encoding='utf-8')
# Safe even when the runtime contains an HTML script closing tag.
literal = json.dumps(runtime, ensure_ascii=True).replace('<', '\\u003c')
source = ('/* GENERATED by build_cavalry.py. Do not edit. */\n' + browser
          + '\nJ.Cavalry.runtimeSource = ' + literal + ';\n')
(ROOT / 'src/11r_cavalry.js').write_text(source, encoding='utf-8')
print('Generated src/11r_cavalry.js')
