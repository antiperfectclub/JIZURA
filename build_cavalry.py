"""Bundle Cavalry's host code for the browser build, the Scripts folder and the loader.

The page only needs the exporter (browser.js) plus the host sources as strings; the two dist files are what a
user installs in Cavalry:

  dist/cavalry/JIZURA_CV.js         panel (dockable, optional WebServer receiver)
  dist/cavalry/JIZURA_CV_Loader.js  one-shot loader (posts to the panel, builds locally when it cannot)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CV = ROOT / 'cavalry'


def read(name):
    return (CV / name).read_text(encoding='utf-8')


families = read('families.js')
browser = read('browser.js')
presets = read('presets.js')
runtime = read('runtime.js')
bridge = read('bridge.js')
panel = read('panel.js')
loader = read('loader.js')

# families.js comes first: presets.js and browser.js both resolve preset names through it.
host = '\n'.join([families, presets, runtime])
panel_tail = '\n'.join([bridge, panel])
loader_tail = '\n'.join([bridge, loader])


def literal(text):
    # Safe even when the source contains an HTML script closing tag.
    return json.dumps(text, ensure_ascii=True).replace('<', '\\u003c')


source = ('/* GENERATED by build_cavalry.py. Do not edit. */\n'
          + families + '\n' + browser
          + '\nJ.Cavalry.runtimeSource = ' + literal(host)
          + ';\nJ.Cavalry.panelSource = ' + literal(panel_tail)
          + ';\nJ.Cavalry.loaderSource = ' + literal(loader_tail) + ';\n')
(ROOT / 'src/11r_cavalry.js').write_text(source, encoding='utf-8')
print('Generated src/11r_cavalry.js')

HEADER = ('/* GENERATED by build_cavalry.py. Install in Cavalry: Help > Show Scripts Folder, '
          'then Window > Scripts. */\n')
dist = ROOT / 'dist' / 'cavalry'
dist.mkdir(parents=True, exist_ok=True)
(dist / 'JIZURA_CV.js').write_text(HEADER + host + '\n' + panel_tail + '\n', encoding='utf-8')
(dist / 'JIZURA_CV_Loader.js').write_text(HEADER + host + '\n' + loader_tail + '\n', encoding='utf-8')
for name in ('JIZURA_CV.js', 'JIZURA_CV_Loader.js'):
    print('Generated dist/cavalry/' + name)
